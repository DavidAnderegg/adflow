        x1 = x3
      end if
      if (x1 .gt. 1.0) then
        f_theta_t = 1.0
      else
        f_theta_t = x1
      end if
      t = 500.0*rlv(i, j, k)/(w(i, j, k, irho)*u2)
! todo: save this in scratch
      r_t = w(i, j, k, irho)*w(i, j, k, itu1)/(rlv(i, j, k)*w(i, j, k, &
