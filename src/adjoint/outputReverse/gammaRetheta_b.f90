&         (-((tu/1.5)**1.5))
      else
        f = 1.0 + 0.275*(1.0-exp(-(35.0*lambda)))*exp(-(tu/0.5))
      end if
      if (tu .gt. 1.3) then
        re_thetat_eq_1 = 331.50*(tu-0.5658)**(-0.671)*f
      else
        re_thetat_eq_1 = (1173.51-589.428*tu+0.2196*tu**(-2))*f
      end if
      re_thetat_eq_2 = w(i, j, k, irho)*u*thetat/rlv(i, j, k)
! residum which should go to 0
      residum = re_thetat_eq_1 - re_thetat_eq_2
      if (residum .ge. 0.) then
        abs0 = residum
      else
        abs0 = -residum
      end if
! exit if converged
      if (abs0 .lt. 1e-9) then
        goto 100
      else
! apply the secant method update
        if (n .gt. 1) then
          if (residum - residum_old .ge. 0.) then
            abs1 = residum - residum_old
          else
            abs1 = -(residum-residum_old)
          end if
          if (abs1 .gt. 1.0e-12) then
            thetat_new = thetat - residum*(thetat_old-thetat)/(&
&             residum_old-residum)
          else
            print*, &
&           'warning: small denominator in secant method, stopping.'
            goto 100
          end if
        else
! initial step
          thetat_new = 0.5*thetat
        end if
! update values for next iteration
        thetat_old = thetat
        residum_old = residum
        thetat = thetat_new
      end if
    end do
 100 if (re_thetat_eq_1 .lt. 20.0) then
      x2 = 20.0
    else
      x2 = re_thetat_eq_1
    end if
    if (x2 .gt. 1.0e10) then
      re_thetat_eq = 1.0e10
    else
      re_thetat_eq = x2
    end if
  end subroutine solve_local_re_thetat_eq

