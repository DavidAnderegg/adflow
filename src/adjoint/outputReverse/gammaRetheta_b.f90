      xad = xp*ttpd + xm*ttmd
      ypd = ya*ttpd
      yad = yp*ttpd + ym*ttmd
      zpd = za*ttpd
      zad = zp*ttpd + zm*ttmd
      xmd = xa*ttmd
      ymd = ya*ttmd
      zmd = za*ttmd
      tempd0 = half*zad
      sjd(i, j, k, 3) = sjd(i, j, k, 3) + voli*tempd0
      sjd(i, j-1, k, 3) = sjd(i, j-1, k, 3) + voli*tempd0
